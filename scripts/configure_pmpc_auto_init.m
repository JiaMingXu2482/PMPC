function configure_pmpc_auto_init()
%CONFIGURE_PMPC_AUTO_INIT Make pmpc_mil runnable from Simulink's Run button.
% Existing PMPC_P in the base workspace is preserved for manual tuning.
startup_pmpc();
model='pmpc_mil';
assert(~bdIsLoaded(model), ...
    'Close loaded pmpc_mil before changing the saved model callback.');
load_system(model);
callback=sprintf([ ...
    'pmpcRoot = fileparts(get_param(bdroot, ''FileName''));\n' ...
    'addpath(pmpcRoot);\n' ...
    'startup_pmpc();\n' ...
    'if evalin(''base'', ''exist(''''PMPC_P'''', ''''var'''') ~= 1'')\n' ...
    '    mil_init_PMPC();\n' ...
    'end\n']);
set_param(model,'InitFcn',callback);
save_system(model);
close_system(model,0);
fprintf('Saved conditional PMPC_P initialization in pmpc_mil.slx.\n');
end
