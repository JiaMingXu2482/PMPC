function nfl = nlcsnn_v14_nfl(u, sigma_v)
%NLCSNN_V14_NFL  Exact 35-feature order of static_nfl_v12.
%#codegen
u = single(u);
x = u(1); v = u(2); a = u(3);
i = u(4); di = u(5); t = u(6);
v_abs = abs(v);
v_pos = max(v, single(0));
v_neg = min(v, single(0));
sgn_v = tanh(v / sigma_v);
slow_gate = exp(-v_abs / sigma_v);
x_abs = abs(x);
nfl = [u(:); ...
    v; x*v; v*i; v*t; ...
    tanh(2*v_pos); tanh(v_pos/sigma_v); i*tanh(v_pos/sigma_v); ...
    v_neg*v_abs; v_neg^3; a*v_neg; i*v_neg*v_abs; ...
    di*v; di*a; abs(di)*i; ...
    sgn_v; i*sgn_v; x^2; x^3; a*i; ...
    abs(a); a*v; abs(a)*sgn_v; i*abs(a); ...
    slow_gate; x*slow_gate; x_abs*slow_gate; ...
    i*x*slow_gate; i*x_abs*slow_gate; sgn_v*x_abs];
end
