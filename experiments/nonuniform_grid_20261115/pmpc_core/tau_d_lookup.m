function tau_d = tau_d_lookup(I_start, I_target, v_rel)
%TAU_D_LOOKUP 由辨识表查一阶时滞 tau [s]。
%#codegen
%
%   tau_d = tau_d_lookup(I_start, I_target, v_rel)
%
%   输入（标量，单角）：
%     I_start  当前电流 [A]，0..1.6
%     I_target 下一拍电流 [A]，0..1.6
%     v_rel    该角压缩速度 [mm/s]，压缩为正，-400..400
%   输出：
%     tau_d    一阶环节时间常数 [s]
%
% 数据来源：pmpc_core/data/tau_table_tau.mat
%   tau_tau(I_start, I_target, v_rel)，由 MR_NLCSNN/SH_delay/build_tau_table.m
%   对减振器正模型做 180 组恒速电流阶跃辨识，再用
%   tau = (t90-t10)/2.1972 换算（t90 直接当 tau 会高估 2.3 倍，见
%   tools/build_tau_table_tau.m 的头注释）。
%
% 为什么是三维表而不是只看速度：
%   四种条件（压缩/复原 x 升/降电流）的 tau 差 2.4 倍，
%   压缩升电流 19.6 ms、压缩降电流 8.2 ms。只看速度幅值会把方向性丢光。
%
% 表格以 coder.const 内联，避免仿真期读文件；更新表时重新生成
% pmpc_core/data/tau_table_tau.mat 并同步这里的数值。

persistent TAU IGRID VGRID
if isempty(TAU)
    IGRID = [0 0.4 0.8 1.2 1.6];
    VGRID = [-400 -300 -200 -100 0 100 200 300 400];
    TAU = build_table();
end

i0 = I_start;  i1 = I_target;  vv = v_rel;

% 夹到网格内
i0 = min(max(i0, IGRID(1)),  IGRID(end));
i1 = min(max(i1, IGRID(1)),  IGRID(end));
vv = min(max(vv, VGRID(1)),  VGRID(end));

% 找包围格与权重（三分量三线性，手工插值，避免 interp3 的 codegen 开销）
[a, fa] = seg(i0, IGRID);
[b, fb] = seg(i1, IGRID);
[c, fc] = seg(vv, VGRID);

t000 = TAU(a,   b,   c  );  t100 = TAU(a+1, b,   c  );
t010 = TAU(a,   b+1, c  );  t110 = TAU(a+1, b+1, c  );
t001 = TAU(a,   b,   c+1);  t101 = TAU(a+1, b,   c+1);
t011 = TAU(a,   b+1, c+1);  t111 = TAU(a+1, b+1, c+1);

c00 = t000*(1-fa) + t100*fa;
c10 = t010*(1-fa) + t110*fa;
c01 = t001*(1-fa) + t101*fa;
c11 = t011*(1-fa) + t111*fa;

c0 = c00*(1-fb) + c10*fb;
c1 = c01*(1-fb) + c11*fb;

tau_d = (c0*(1-fc) + c1*fc) * 1e-3;      % ms -> s
tau_d = max(tau_d, 1e-4);                 % 与常数口径一致的下限
end

function [k, f] = seg(x, grid)
%SEG 标量落在第 k..k+1 格，返回起点下标与相对位置 f in [0,1]。
n = numel(grid);
k = 1;
for j = 1:n-1
    if x >= grid(j)
        k = j;
    end
end
k = min(max(k,1), n-1);
d = grid(k+1) - grid(k);
if d <= 0
    f = 0;
else
    f = (x - grid(k))/d;
end
f = min(max(f,0),1);
end

